/// Map a child playback interval into a parent stage's time-code domain using
/// OpenUSD's composed rate ratio (`parent_tcps / child_tcps`) and reference
/// `LayerOffset` (`offset + scale * ratio * t`).
///
/// Rejects non-finite rates/offsets and zero scale. Negative scales are mapped
/// cleanly with ordered `[min, max]` endpoints.
pub(crate) fn map_child_domain_to_parent(
    child_range: TimeCodeRange,
    child_tcps: f64,
    parent_tcps: f64,
    reference_offset: sdf::LayerOffset,
) -> Result<TimeCodeRange> {
    ensure!(
        child_tcps.is_finite() && child_tcps > 0.0,
        "child timeCodesPerSecond must be finite and positive (got {child_tcps})"
    );
    ensure!(
        parent_tcps.is_finite() && parent_tcps > 0.0,
        "parent timeCodesPerSecond must be finite and positive (got {parent_tcps})"
    );
    ensure!(
        reference_offset.offset.is_finite(),
        "reference layer offset must be finite (got {})",
        reference_offset.offset
    );
    ensure!(
        reference_offset.scale.is_finite() && reference_offset.scale != 0.0,
        "reference layer scale must be finite and non-zero (got {})",
        reference_offset.scale
    );

    let rate_scale = parent_tcps / child_tcps;
    ensure!(
        rate_scale.is_finite() && rate_scale > 0.0,
        "unrepresentable effective time rate"
    );
    let effective = reference_offset.concatenate(&sdf::LayerOffset::scale_only(rate_scale));
    ensure!(
        effective.scale.is_finite() && effective.scale != 0.0,
        "unrepresentable effective reference time scale"
    );
    let mapped_start = effective.apply(child_range.start);
    let mapped_end = effective.apply(child_range.end);
    ensure!(
        mapped_start.is_finite() && mapped_end.is_finite(),
        "mapped parent playback range overflowed finite bounds"
    );
    ensure!(
        !child_range.is_non_empty() || mapped_start != mapped_end,
        "mapped positive playback interval collapsed at parent precision"
    );
    child_range.duration_seconds(child_tcps)?;
    let mapped = TimeCodeRange::new(mapped_start.min(mapped_end), mapped_start.max(mapped_end))?;
    mapped.duration_seconds(parent_tcps)?;
    Ok(mapped)
}

/// Returns `true` when the stage carries an authored playback range that was
/// not generated by USDHub (or was manually edited away from the recorded
/// generated range). Such intentional user bounds are never overwritten.
pub(crate) fn has_intentional_authored_range(stage: &Stage) -> Result<bool> {
    if !stage.has_authored_time_code_range() {
        return Ok(stage
            .has_authored_stage_metadata(sdf::FieldKey::StartTimeCode.as_str())?
            || stage.has_authored_stage_metadata(sdf::FieldKey::EndTimeCode.as_str())?);
    }
    let root = stage.prim(format!("/{SCENE_ROOT_PRIM}").as_str())?;
    let Some(Value::Dictionary(custom_data)) = root.metadata::<Value>("customData")? else {
        return Ok(true);
    };
    let is_generated = custom_data
        .get(TIMELINE_RANGE_MODE_METADATA)
        .and_then(Value::as_str)
        == Some(TIMELINE_RANGE_MODE_GENERATED);
    if !is_generated {
        return Ok(true);
    }
    let Some(generated_start) = dictionary_f64(&custom_data, GENERATED_START_METADATA) else {
        return Ok(true);
    };
    let Some(generated_end) = dictionary_f64(&custom_data, GENERATED_END_METADATA) else {
        return Ok(true);
    };
    let start_matches = stage.start_time_code() == generated_start;
    let end_matches = stage.end_time_code() == generated_end;
    Ok(!(start_matches && end_matches))
}

/// Observation of directly authored attribute `timeSamples` in a stage's own
/// root layer, separating sample presence from positive playback span.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct RootLayerSampleObservation {
    pub has_authored_samples: bool,
    pub positive_span: Option<TimeCodeRange>,
}

/// Scan the stage's own root layer for directly authored attribute `timeSamples`
/// (parent-owned animation such as animated cameras or member placement motion)
/// without descending into referenced external layers.
pub(crate) fn inspect_root_layer_authored_samples(
    stage: &Stage,
) -> Result<RootLayerSampleObservation> {
    let root_layer = stage.root_layer();
    let Some(pseudo_root) = root_layer.pseudo_root()? else {
        return Ok(RootLayerSampleObservation {
            has_authored_samples: false,
            positive_span: None,
        });
    };
    let mut stack: Vec<sdf::Path> = pseudo_root
        .prim_children()?
        .unwrap_or_default()
        .into_iter()
        .map(|child| sdf::path(format!("/{}", child.as_str())))
        .collect::<std::result::Result<Vec<_>, _>>()?;

    let mut has_authored_samples = false;
    let mut min_time = f64::INFINITY;
    let mut max_time = f64::NEG_INFINITY;

    while let Some(prim_path) = stack.pop() {
        let prim_spec = root_layer
            .prim(prim_path.clone())?
            .with_context(|| format!("missing authored playback prim {prim_path}"))?;
        if let Some(properties) = prim_spec.property_children()? {
            for prop in properties {
                let attr_path = sdf::path(format!("{}.{}", prim_path.as_str(), prop.as_str()))?;
                if let Some(attr_spec) = root_layer.attribute(attr_path.clone())?
                    && let Some(samples) = attr_spec.time_samples()?
                {
                    for (time, _) in samples {
                        ensure!(
                            time.is_finite(),
                            "non-finite authored sample on {attr_path}"
                        );
                        has_authored_samples = true;
                        min_time = min_time.min(time);
                        max_time = max_time.max(time);
                    }
                }
            }
        }
        if let Some(children) = prim_spec.prim_children()? {
            for child in children {
                stack.push(sdf::path(format!(
                    "{}/{}",
                    prim_path.as_str(),
                    child.as_str()
                ))?);
            }
        }
    }

    let positive_span = if has_authored_samples && max_time > min_time {
        Some(TimeCodeRange::new(min_time, max_time)?)
    } else {
        None
    };
    Ok(RootLayerSampleObservation {
        has_authored_samples,
        positive_span,
    })
}

/// Return the positive playback span of directly authored root-layer
/// `timeSamples`, if any.
pub(crate) fn root_layer_authored_time_sample_range(stage: &Stage) -> Result<Option<TimeCodeRange>> {
    Ok(inspect_root_layer_authored_samples(stage)?.positive_span)
}

/// Read the reference offset for a required managed occurrence. Absence of
/// the expected member/reference is an error, not an identity time mapping.
pub(crate) fn read_member_reference_offset(
    stage: &Stage,
    member_id: SceneMemberId,
) -> Result<sdf::LayerOffset> {
    let member_path = scene_member_path_for_stage(stage, member_id)?;
    read_prim_reference_offset(stage, &member_path)?
        .with_context(|| format!("missing managed Scene member {member_id}"))
}

/// During creation only, a genuinely absent member has no prior time offset.
pub(crate) fn existing_member_reference_offset(
    stage: &Stage,
    member_id: SceneMemberId,
) -> Result<sdf::LayerOffset> {
    let member_path = scene_member_path_for_stage(stage, member_id)?;
    Ok(read_prim_reference_offset(stage, &member_path)?.unwrap_or(sdf::LayerOffset::IDENTITY))
}

fn read_prim_reference_offset(stage: &Stage, prim_path: &str) -> Result<Option<sdf::LayerOffset>> {
    Ok(read_prim_reference(stage, prim_path)?.map(|reference| reference.layer_offset))
}

fn read_prim_reference(stage: &Stage, prim_path: &str) -> Result<Option<sdf::Reference>> {
    let root_layer = stage.root_layer();
    let spec_path = sdf::path(prim_path)?;
    let Some(spec) = root_layer.prim(spec_path)? else {
        return Ok(None);
    };
    let Some(Value::ReferenceListOp(references)) = spec.field(REFERENCES_FIELD)? else {
        bail!("managed member {prim_path} is missing its reference list");
    };
    let mut references = references.iter();
    let reference = references
        .next()
        .with_context(|| format!("empty reference list on {prim_path}"))?;
    ensure!(
        references.next().is_none(),
        "ambiguous managed member reference on {prim_path}"
    );
    ensure!(
        reference.layer_offset.offset.is_finite()
            && reference.layer_offset.scale.is_finite()
            && reference.layer_offset.scale != 0.0,
        "invalid time offset on {prim_path}"
    );
    Ok(Some(reference.clone()))
}

/// Verify the same occurrence whose domain is read from the canonical or staged
/// managed child. The reference is authored relative to the final layer, never
/// relative to a transaction's temporary export directory.
fn verified_member_reference_offset(
    stage: &Stage,
    project_root: &Path,
    final_layer_path: &Path,
    member: &SceneMember,
    overrides: &TimelineStageOverrides,
) -> Result<sdf::LayerOffset> {
    let member_path = scene_member_path_for_stage(stage, member.id)?;
    let reference = read_prim_reference(stage, &member_path)?
        .with_context(|| format!("missing managed occurrence {}", member.id))?;
    let (target_path, target_prim) = match member.target {
        SceneMemberTarget::Scene(id) => (
            overrides
                .scene_targets
                .get(&id)
                .cloned()
                .unwrap_or_else(|| scene_path(project_root, id)),
            "/SceneRoot",
        ),
        SceneMemberTarget::Model(id) => (
            overrides
                .model_targets
                .get(&id)
                .cloned()
                .unwrap_or_else(|| model_wrapper_path(project_root, id)),
            "/ModelRoot",
        ),
    };
    let expected = crate::project::storage::authored_relative_project_asset_path(
        project_root,
        final_layer_path,
        &target_path,
    )?;
    let actual_asset = Path::new(&reference.asset_path);
    ensure!(
        !reference.asset_path.is_empty() && !actual_asset.is_absolute(),
        "managed occurrence {} must use a relative Project asset",
        member.id
    );
    let actual_target = final_layer_path
        .parent()
        .context("Scene layer has no parent directory")?
        .join(actual_asset);
    let actual = crate::project::storage::authored_relative_project_asset_path(
        project_root,
        final_layer_path,
        &actual_target,
    )?;
    ensure!(
        actual == expected && reference.prim_path.as_str() == target_prim,
        "managed occurrence {} reference mismatch: expected {} {}, got {} {}",
        member.id,
        expected,
        target_prim,
        reference.asset_path,
        reference.prim_path
    );
    Ok(reference.layer_offset)
}

/// Recompute and apply aggregated playback-timeline metadata on an open parent
/// Scene stage from its parent-authored animation and referenced members.
///
/// Intentional user-authored bounds are preserved unchanged, but required
/// wrapper source and managed occurrence dependencies are always qualified
/// before returning.
pub(crate) fn recompute_scene_stage_timeline(
    stage: &Stage,
    project_root: &Path,
    final_layer_path: &Path,
    members: &[SceneMember],
    overrides: &TimelineStageOverrides,
) -> Result<TimelineUpdateOutcome> {
    let intentional = has_intentional_authored_range(stage)?;
    let parent_meta = inspect_stage_time_metadata(stage, false)?;
    let parent_tcps = parent_meta.time_codes_per_second;
    ensure!(
        parent_tcps.is_finite() && parent_tcps > 0.0,
        "parent Scene timeCodesPerSecond must be finite and positive (got {parent_tcps})"
    );

    let aggregated = aggregate_member_domains(
        stage,
        project_root,
        final_layer_path,
        members,
        parent_tcps,
        overrides,
        |member| {
            let staged = match member.target {
                SceneMemberTarget::Scene(id) => overrides.scenes.get(&id),
                SceneMemberTarget::Model(id) => overrides.models.get(&id),
            };
            let child_path = staged.cloned().unwrap_or_else(|| match member.target {
                SceneMemberTarget::Scene(id) => overrides
                    .scene_targets
                    .get(&id)
                    .cloned()
                    .unwrap_or_else(|| scene_path(project_root, id)),
                SceneMemberTarget::Model(id) => overrides
                    .model_targets
                    .get(&id)
                    .cloned()
                    .unwrap_or_else(|| model_wrapper_path(project_root, id)),
            });
            ensure!(
                child_path.is_file(),
                "required playback layer for member {} is missing: {}",
                member.id,
                child_path.display()
            );
            // Staged managed layers have already had their temporal metadata
            // resolved by their authoring owner. Their asset paths are relative to
            // the final canonical destination, not the transaction directory.
            if staged.is_some() {
                let child = Stage::builder()
                    .load(InitialLoadSet::LoadNone)
                    .open(child_path.to_string_lossy().as_ref())?;
                inspect_stage_time_metadata(&child, false)
            } else {
                let child_stage = Stage::builder()
                    .load(InitialLoadSet::LoadNone)
                    .open(child_path.to_string_lossy().as_ref())?;
                let child_root_prim = match member.target {
                    SceneMemberTarget::Scene(_) => SCENE_ROOT_PRIM,
                    SceneMemberTarget::Model(_) => MODEL_ROOT_PRIM,
                };
                if let Some(source_path) =
                    resolve_wrapper_source_path(&child_stage, &child_path, child_root_prim)?
                {
                    ensure!(
                        source_path.is_file(),
                        "required wrapper source for member {} is missing: {}",
                        member.id,
                        source_path.display()
                    );
                }
                inspect_source_time_metadata(&child_path)
            }
            .with_context(|| {
                format!(
                    "inspect child playback metadata for member {} ({})",
                    member.id,
                    child_path.display()
                )
            })
        },
    )?;

    if intentional {
        return Ok(TimelineUpdateOutcome::PreservedUserRange);
    }
    apply_generated_timeline(stage, parent_tcps, aggregated)
}

pub(super) fn aggregate_member_domains(
    stage: &Stage,
    project_root: &Path,
    final_layer_path: &Path,
    members: &[SceneMember],
    parent_tcps: f64,
    overrides: &TimelineStageOverrides,
    mut inspect: impl FnMut(&SceneMember) -> Result<StageTimeMetadata>,
) -> Result<Option<TimeCodeRange>> {
    let mut aggregated = root_layer_authored_time_sample_range(stage)?;
    // An adopted Scene owns a source occurrence in addition to managed members.
    if let Some(source) =
        wrapper_source_domain(stage, final_layer_path, SCENE_ROOT_PRIM, parent_tcps)?
    {
        aggregated = union_ranges(aggregated, source);
    }
    for member in members {
        let reference_offset = verified_member_reference_offset(
            stage,
            project_root,
            final_layer_path,
            member,
            overrides,
        )?;
        let child_meta = inspect(member)?;
        let Some(child_range) = child_meta.range.filter(|range| range.is_non_empty()) else {
            continue;
        };
        let mapped = map_child_domain_to_parent(
            child_range,
            child_meta.time_codes_per_second,
            parent_tcps,
            reference_offset,
        )?;
        aggregated = Some(match aggregated {
            Some(current) => current.union(mapped),
            None => mapped,
        });
    }
    if let Some(range) = aggregated {
        range.duration_seconds(parent_tcps)?;
    }
    Ok(aggregated)
}

/// Linked refresh replaces a wrapper rather than merging authored Scene specs.
/// Preserve a deliberate range override, and refuse a destructive refresh of
/// locally animated or composed Scenes until the existing authoring owner can
/// merge their authored opinions with the refreshed source.
pub(crate) fn preserve_linked_scene_timeline(
    existing_path: &Path,
    candidate_path: &Path,
    scene_id: SceneId,
) -> Result<()> {
    let existing = Stage::open(existing_path.to_string_lossy().as_ref())?;
    ensure!(
        read_scene_members(existing_path, scene_id)?.is_empty(),
        "linked Scene refresh would discard locally authored members"
    );
    let local_samples = inspect_root_layer_authored_samples(&existing)?;
    ensure!(
        !local_samples.has_authored_samples,
        "linked Scene refresh would discard locally authored animation"
    );
    if !has_intentional_authored_range(&existing)? {
        return Ok(());
    }
    let metadata = inspect_stage_time_metadata(&existing, false)?;
    let candidate = Stage::open(candidate_path.to_string_lossy().as_ref())?;
    crate::document::stages::metadata::apply_stage_time_metadata(&candidate, metadata)?;
    let root = candidate.prim(format!("/{SCENE_ROOT_PRIM}").as_str())?;
    if let Some(Value::Dictionary(mut data)) = root.metadata::<Value>("customData")? {
        data.remove(TIMELINE_RANGE_MODE_METADATA);
        data.remove(GENERATED_START_METADATA);
        data.remove(GENERATED_END_METADATA);
        root.set_metadata("customData", Value::Dictionary(data))?;
    }
    candidate
        .root_layer()
        .export(candidate_path.to_string_lossy().as_ref())?;
    Ok(())
}

fn union_ranges(a: Option<TimeCodeRange>, b: Option<TimeCodeRange>) -> Option<TimeCodeRange> {
    match (a, b) {
        (Some(a), Some(b)) => Some(a.union(b)),
        (Some(range), None) | (None, Some(range)) => Some(range),
        (None, None) => None,
    }
}

/// At initial wrapper authoring the source metadata has already been resolved
/// against its staged source closure. Mark the copied bounds as generated before
/// any managed membership can be added; never mark an existing legacy range.
pub(crate) fn mark_new_adopted_source_timeline(stage: &Stage) -> Result<()> {
    let metadata = inspect_stage_time_metadata(stage, false)?;
    apply_generated_timeline(stage, metadata.time_codes_per_second, metadata.range)?;
    Ok(())
}

pub(super) fn apply_generated_timeline(
    stage: &Stage,
    parent_tcps: f64,
    next_range: Option<TimeCodeRange>,
) -> Result<TimelineUpdateOutcome> {
    let current_range = if stage.has_authored_time_code_range() {
        Some(TimeCodeRange::new(
            stage.start_time_code(),
            stage.end_time_code(),
        )?)
    } else {
        None
    };
    let same_range = match (current_range, next_range) {
        (Some(a), Some(b)) => a == b,
        (None, None) => true,
        _ => false,
    };

    let root = stage.prim(format!("/{SCENE_ROOT_PRIM}").as_str())?;
    let mut custom_data = match root.metadata::<Value>("customData")? {
        Some(Value::Dictionary(data)) => data,
        _ => openusd::vt::Dictionary::new(),
    };
    let has_generated_markers = custom_data.contains_key(TIMELINE_RANGE_MODE_METADATA)
        || custom_data.contains_key(GENERATED_START_METADATA)
        || custom_data.contains_key(GENERATED_END_METADATA);

    match next_range {
        Some(range) => {
            let markers_match = custom_data
                .get(TIMELINE_RANGE_MODE_METADATA)
                .and_then(Value::as_str)
                == Some(TIMELINE_RANGE_MODE_GENERATED)
                && dictionary_f64(&custom_data, GENERATED_START_METADATA)
                    .is_some_and(|v| v == range.start)
                && dictionary_f64(&custom_data, GENERATED_END_METADATA)
                    .is_some_and(|v| v == range.end);
            let tcps_authored = stage
                .has_authored_stage_metadata(sdf::FieldKey::TimeCodesPerSecond.as_str())?;
            if same_range && markers_match && tcps_authored {
                return Ok(TimelineUpdateOutcome::Unchanged(Some(range)));
            }
            stage.set_start_time_code(range.start)?;
            stage.set_end_time_code(range.end)?;
            stage.set_time_codes_per_second(parent_tcps)?;
            custom_data.insert(
                TIMELINE_RANGE_MODE_METADATA.to_owned(),
                Value::String(TIMELINE_RANGE_MODE_GENERATED.to_owned()),
            );
            custom_data.insert(
                GENERATED_START_METADATA.to_owned(),
                Value::Double(range.start),
            );
            custom_data.insert(GENERATED_END_METADATA.to_owned(), Value::Double(range.end));
            root.set_metadata("customData", Value::Dictionary(custom_data))?;
            Ok(TimelineUpdateOutcome::Updated(Some(range)))
        }
        None => {
            if same_range && !has_generated_markers {
                return Ok(TimelineUpdateOutcome::Unchanged(None));
            }
            if stage.has_authored_stage_metadata(sdf::FieldKey::StartTimeCode.as_str())? {
                stage.clear_stage_metadata(sdf::FieldKey::StartTimeCode.as_str())?;
            }
            if stage.has_authored_stage_metadata(sdf::FieldKey::EndTimeCode.as_str())? {
                stage.clear_stage_metadata(sdf::FieldKey::EndTimeCode.as_str())?;
            }
            if has_generated_markers {
                custom_data.remove(TIMELINE_RANGE_MODE_METADATA);
                custom_data.remove(GENERATED_START_METADATA);
                custom_data.remove(GENERATED_END_METADATA);
                root.set_metadata("customData", Value::Dictionary(custom_data))?;
            }
            Ok(TimelineUpdateOutcome::Updated(None))
        }
    }
}

/// Identify an authored wrapper by its own transparent Source role. A prim
/// named Source alone is not a wrapper. Collect all locally authored reference
/// arcs, rather than accepting the first reference in a malformed wrapper.
fn wrapper_source_references(
    stage: &Stage,
    root_prim_name: &str,
) -> Result<Option<Vec<sdf::Reference>>> {
    use crate::project::assets::spatial::{
        USDHUB_HIERARCHY_ROLE_METADATA, USDHUB_TRANSPARENT_SOURCE_ROLE,
    };
    let source_path = format!("/{root_prim_name}/{SOURCE_PRIM}");
    let root_layer = stage.root_layer();
    let Some(spec) = root_layer.prim(sdf::path(&source_path)?)? else {
        return Ok(None);
    };
    let marked = match spec.field("customData")? {
        Some(Value::Dictionary(data)) => {
            data.get(USDHUB_HIERARCHY_ROLE_METADATA)
                .and_then(Value::as_str)
                == Some(USDHUB_TRANSPARENT_SOURCE_ROLE)
        }
        _ => false,
    };
    if !marked {
        return Ok(None);
    }
    let mut references = Vec::new();
    if let Some(reference) = if spec.has_field(REFERENCES_FIELD)? {
        read_prim_reference(stage, &source_path)?
    } else {
        None
    } {
        references.push(reference);
    }
    if let Some(children) = spec.prim_children()? {
        for child in children {
            let path = format!("{source_path}/{}", child.as_str());
            let child_spec = root_layer
                .prim(sdf::path(&path)?)?
                .with_context(|| format!("missing authored Source child {path}"))?;
            if child_spec.has_field(REFERENCES_FIELD)? {
                references.push(
                    read_prim_reference(stage, &path)?.context("missing Source child reference")?,
                );
            }
        }
    }
    let first = references
        .first()
        .context("marked Source has no authored reference")?;
    ensure!(
        !first.asset_path.is_empty(),
        "Source reference has no asset path"
    );
    ensure!(
        references
            .iter()
            .all(|reference| reference.asset_path == first.asset_path
                && !reference.prim_path.as_str().is_empty()),
        "unsupported ambiguous Source references"
    );
    Ok(Some(references))
}

pub(super) fn resolve_wrapper_source_path(
    stage: &Stage,
    wrapper_path: &Path,
    root_prim_name: &str,
) -> Result<Option<PathBuf>> {
    let Some(references) = wrapper_source_references(stage, root_prim_name)? else {
        return Ok(None);
    };
    let reference = references
        .first()
        .context("missing wrapper source reference")?;
    let base = wrapper_path
        .parent()
        .context("wrapper layer has no parent directory")?;
    Ok(Some(base.join(&reference.asset_path)))
}

/// `None` means ordinary Scene; `Some(None)` means a qualified static source.
fn wrapper_source_domain(
    stage: &Stage,
    wrapper_path: &Path,
    root_prim_name: &str,
    parent_rate: f64,
) -> Result<Option<Option<TimeCodeRange>>> {
    let Some(references) = wrapper_source_references(stage, root_prim_name)? else {
        return Ok(None);
    };
    let reference = references
        .first()
        .context("missing wrapper source reference")?;
    let base = wrapper_path
        .parent()
        .context("wrapper layer has no parent directory")?;
    let source_path = base.join(&reference.asset_path);
    let source = inspect_source_time_metadata(&source_path)
        .with_context(|| format!("inspect wrapper source {}", source_path.display()))?;
    let mut range = None;
    if let Some(source_range) = source.range.filter(|range| range.is_non_empty()) {
        for reference in references {
            let mapped = map_child_domain_to_parent(
                source_range,
                source.time_codes_per_second,
                parent_rate,
                reference.layer_offset,
            )?;
            range = union_ranges(range, Some(mapped));
        }
    }
    Ok(Some(range))
}

fn dictionary_f64(data: &openusd::vt::Dictionary, key: &str) -> Option<f64> {
    match data.get(key) {
        Some(Value::Double(value)) => Some(*value),
        Some(Value::Float(value)) => Some(f64::from(*value)),
        _ => None,
    }
}
